#!/usr/bin/env python3
"""Vendor Google Chrome's Modern Web Guidance skills at a pinned release.

    python3 scripts/sync_modern_web_guidance.py --ref v1.0.0            # sync
    python3 scripts/sync_modern_web_guidance.py --ref v1.0.0 --source DIR
    python3 scripts/sync_modern_web_guidance.py --check                 # verify

Sync clones (or reads --source, an existing clone) at an exact tag or commit,
refuses moving refs such as `latest` or a branch, scans the upstream files for
hidden Unicode, and copies only Markdown and the LICENSE (scripts such as
legacy-scan.mjs are skipped and listed in VENDORED.json). It never runs npm,
npx or any upstream code. Google's text is copied byte for byte; vstack-owned
files (SKILL.md, NOTICE.md) are left alone. Each skill folder gets a generated
VENDORED.json (pinned commit plus SHA-256 of every vendored file); the main
skill also gets INDEX.md (guide id, path, title) for local lookup.
--check recomputes the hashes and fails on any drift.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
SKILLS_DIR = REPO_ROOT / "skills"
UPSTREAM_URL = "https://github.com/GoogleChrome/modern-web-guidance.git"
UPSTREAM_REPO = "GoogleChrome/modern-web-guidance"

# upstream skill folder -> how its files land in vstack's folder of the same name.
# The upstream SKILL.md is renamed so agent hosts never load its trigger, which
# tells agents to run `npx modern-web-guidance@latest` first on every web task.
SKILLS = {
    "modern-web-guidance": {"SKILL.md": "UPSTREAM_SKILL.md"},
    "chrome-extensions": {"SKILL.md": "GUIDE.md"},
}
VSTACK_OWNED = frozenset({"SKILL.md", "NOTICE.md"})
GENERATED = frozenset({"VENDORED.json", "INDEX.md"})
ALLOWED_SUFFIXES = frozenset({".md"})

# Zero-width, bidi-control, word-joiner, BOM and tag characters: invisible text
# that can hide instructions from a human reviewer.
HIDDEN_RE = re.compile("[​-‏‪-‮⁠-⁤﻿\U000e0000-\U000e007f]")
EXACT_REF_RE = re.compile(r"^(v\d+\.\d+\.\d+|[0-9a-f]{40})$")


class SyncError(Exception):
    pass


def git(*args: str, cwd: Path) -> str:
    return subprocess.run(
        ["git", *args], cwd=cwd, check=True, capture_output=True, text=True
    ).stdout.strip()


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def validate_ref(ref: str) -> None:
    if not EXACT_REF_RE.match(ref):
        raise SyncError(
            f"--ref {ref!r} is not an exact release tag (vX.Y.Z) or a full 40-character commit; "
            "moving refs such as latest or main are refused"
        )


def scan(src_root: Path) -> list[str]:
    """Problems that block a sync: hidden Unicode in any file we would copy."""
    problems = []
    for skill, spec in SKILLS.items():
        base = src_root / "skills" / skill
        for path in upstream_files(base, spec):
            if skipped(path):
                continue
            text = path.read_text(encoding="utf-8")
            for n, line in enumerate(text.splitlines(), 1):
                if HIDDEN_RE.search(line):
                    problems.append(f"{path.relative_to(src_root)}:{n}: hidden Unicode character")
    return problems


def upstream_files(base: Path, spec: dict) -> list[Path]:
    if not (base / "SKILL.md").is_file():
        raise SyncError(f"upstream is missing {base.name}/SKILL.md")
    return sorted(p for p in base.rglob("*") if p.is_file())


def skipped(path: Path) -> bool:
    return path.suffix not in ALLOWED_SUFFIXES


def guide_index(dest: Path) -> str:
    rows = []
    for path in sorted((dest / "guides").rglob("*.md")):
        title = next(
            (l[2:].strip() for l in path.read_text(encoding="utf-8").splitlines() if l.startswith("# ")),
            path.stem,
        )
        rows.append(f"| `{path.stem}` | `{path.relative_to(dest).as_posix()}` | {title} |")
    ids = [r.split("`")[1] for r in rows]
    dupes = sorted({i for i in ids if ids.count(i) > 1})
    if dupes:
        raise SyncError(f"guide ids are not unique: {dupes}")
    return (
        "# Guide index\n\n"
        "Generated by `scripts/sync_modern_web_guidance.py`; do not edit. "
        "A guide id is its file name without `.md`.\n\n"
        "| id | file | title |\n| --- | --- | --- |\n" + "\n".join(rows) + "\n"
    )


def write_manifest(dest: Path, tag: str, commit: str, files: list[str], skipped_files: list[str]) -> None:
    hashes = {f: sha256(dest / f) for f in sorted(files)}
    digest = hashlib.sha256(
        "".join(f"{h}  {f}\n" for f, h in hashes.items()).encode()
    ).hexdigest()
    manifest = {
        "upstream": UPSTREAM_REPO,
        "skill": dest.name,
        "tag": tag,
        "commit": commit,
        "license": "Apache-2.0",
        "digest": digest,
        "skipped": sorted(skipped_files),
        "files": hashes,
    }
    (dest / "VENDORED.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")


def sync(src_root: Path, tag: str, commit: str, skills_dir: Path = SKILLS_DIR) -> None:
    problems = scan(src_root)
    if problems:
        raise SyncError("upstream scan failed:\n" + "\n".join(problems))
    for skill, spec in SKILLS.items():
        base = src_root / "skills" / skill
        dest = skills_dir / skill
        dest.mkdir(parents=True, exist_ok=True)
        # Remove everything the last sync wrote, so files dropped upstream go too.
        for child in dest.iterdir():
            if child.name in VSTACK_OWNED:
                continue
            shutil.rmtree(child) if child.is_dir() else child.unlink()
        copied, skipped_files = [], []
        for path in upstream_files(base, spec):
            rel = path.relative_to(base)
            if skipped(path):
                skipped_files.append(rel.as_posix())
                continue
            out = spec["SKILL.md"] if rel.as_posix() == "SKILL.md" else rel.as_posix()
            (dest / out).parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(path, dest / out)
            copied.append(out)
        shutil.copyfile(src_root / "LICENSE", dest / "LICENSE")
        copied.append("LICENSE")
        if skill == "modern-web-guidance":
            (dest / "INDEX.md").write_text(guide_index(dest), encoding="utf-8")
        write_manifest(dest, tag, commit, copied, skipped_files)
        missing = VSTACK_OWNED - {p.name for p in dest.iterdir()}
        if missing:
            print(f"warning: {skill} has no vstack-owned {sorted(missing)}; write them by hand", file=sys.stderr)
        print(f"{skill}: {len(copied)} files at {tag} ({commit[:7]}), {len(skipped_files)} skipped")


def check(skills_dir: Path = SKILLS_DIR) -> list[str]:
    errors = []
    for skill in SKILLS:
        dest = skills_dir / skill
        manifest_path = dest / "VENDORED.json"
        if not manifest_path.is_file():
            errors.append(f"{skill}: VENDORED.json missing")
            continue
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        expected = manifest["files"]
        for rel, digest in expected.items():
            path = dest / rel
            if not path.is_file():
                errors.append(f"{skill}/{rel}: missing")
            elif sha256(path) != digest:
                errors.append(f"{skill}/{rel}: changed since sync (Google's text must stay unmodified)")
        allowed = set(expected) | VSTACK_OWNED | GENERATED
        for path in dest.rglob("*"):
            rel = path.relative_to(dest).as_posix()
            if path.is_file() and rel not in allowed:
                errors.append(f"{skill}/{rel}: not from the pinned upstream and not vstack-owned")
        if skill == "modern-web-guidance" and (dest / "INDEX.md").read_text(encoding="utf-8") != guide_index(dest):
            errors.append(f"{skill}/INDEX.md: stale; rerun the sync")
    return errors


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--ref", help="exact upstream tag (vX.Y.Z) or 40-character commit")
    parser.add_argument("--source", type=Path, help="existing upstream clone (default: clone into a temp dir)")
    parser.add_argument("--check", action="store_true", help="verify vendored files against VENDORED.json")
    args = parser.parse_args(argv)
    try:
        if args.check:
            errors = check()
            for e in errors:
                print(e, file=sys.stderr)
            if not errors:
                print("modern-web-guidance vendor check OK")
            return 1 if errors else 0
        if not args.ref:
            parser.error("--ref is required unless --check")
        validate_ref(args.ref)
        with tempfile.TemporaryDirectory() as tmp:
            src = args.source
            if src is None:
                src = Path(tmp) / "upstream"
                subprocess.run(["git", "clone", "--quiet", UPSTREAM_URL, str(src)], check=True)
            git("-c", "advice.detachedHead=false", "checkout", "--quiet", args.ref, cwd=src)
            commit = git("rev-parse", "HEAD", cwd=src)
            tag = args.ref if args.ref.startswith("v") else git("describe", "--tags", "--always", cwd=src)
            sync(src, tag, commit)
        return 0
    except (SyncError, subprocess.CalledProcessError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
